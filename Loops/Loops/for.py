#For loops iterate over a given sequence. Here is an example:
#The "in" operator could be used to check if 
# a specified object exists within an iterable 
# object container, such as a list:

primes = [2, 3, 5, 7]
for prime in primes:
    print(prime)

#basically prime variable has no value but since we put it in FOR and in
#it repeatedly check primes variable until its done and assign it to prime
